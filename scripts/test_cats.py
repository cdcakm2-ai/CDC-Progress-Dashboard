def classify_activity(text):
    text_lower = text.lower()
    for cat_id, cat_name, keywords in CATEGORIES:
        for kw in keywords:
            if kw in text_lower:
                return cat_id, cat_name
    return "unconfirmed", "වර්ගීකරණය තහවුරු කළ යුතුයි"

from test_extractor import raw_activities
from collections import Counter
c = Counter()
other = []
for a in raw_activities:
    cid, cname = classify_activity(a['description'])
    c[cname] += 1
    if cid == "unconfirmed":
        other.append(a['description'])

print("Enriched Category Counts:")
for name, count in c.most_common():
    print(f"  {name}: {count} ({count/len(raw_activities)*100:.1f}%)")
print(f"Remaining uncategorized: {len(other)}")
for i, o in enumerate(other, 1):
    print(f"  {i}. {o}")
